func RegisterRename(b *bot.Bot) {
	b.OnCommand("随机取名").Plugin(catalog.PluginRandomRename).Handle(func(ctx *bot.CommandContext) error {
		return handleRename(ctx, ctx.Args)
	})
}

func handleRename(ctx renameContext, args []string) error {
	name := ""
	if len(args) > 0 {
		name = args[0]
	}
	if name == "" {
		name = randomName()
	}
	return ctx.SetGroupCard(ctx.GroupID(), ctx.UserID(), name)
}

func randomName() string {
	dictionary := nameDictionaries[rand.Intn(len(nameDictionaries))]
	return dictionary.first[rand.Intn(len(dictionary.first))] +
		dictionary.second[rand.Intn(len(dictionary.second))] +
		dictionary.third[rand.Intn(len(dictionary.third))]
}
